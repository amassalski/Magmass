#ifndef METADANEKSIAZEK_H
#define METADANEKSIAZEK_H

#include <string>

/**
 * Metadane książki odczytane z pliku: XMP z plików PDF (dc:title, dc:creator, dc:publisher, dc:date, prism:isbn,
 * dc:subject...), słownik Info PDF (przez `pdfinfo`) oraz metadane OPF z plików EPUB (Dublin Core).
 */
namespace MetadaneKsiazek {

struct Dane {
    std::string tytul;
    std::string autor;       ///< wielu autorów rozdzielonych przecinkami
    std::string wydawca;
    int rok = 0;
    std::string wydanie;     ///< np. "Wyd. 2" (z BN, pole MARC 250)
    std::string isbn;
    std::string jezyk;       ///< np. "polski" (z kodu "pl")
    std::string tagi;        ///< słowa kluczowe po przecinku
    std::string opis;

    bool pusta() const { return tytul.empty() && autor.empty() && wydawca.empty() && rok == 0 && wydanie.empty() && isbn.empty() && jezyk.empty() && tagi.empty() && opis.empty(); }
};

/// Pakiet XMP (<x:xmpmeta>...</x:xmpmeta>) z surowych bajtów pliku PDF; pusty, gdy go nie ma
std::string wytnijXMP(const std::string& bajty);
/// Dane z XMP (też zapis atrybutowy, rdf:Alt/Seq/Bag z rdf:li)
Dane zXMP(const std::string& xml);
/// Dane z pliku OPF (EPUB)
Dane zOPF(const std::string& xml);
/// Dane z wyjścia `pdfinfo` (wiersze "Title:  ...", "Author:", "Subject:", "Keywords:", "CreationDate:")
Dane zInfoPDF(const std::string& wyjscie);
/// @p pierwszy uzupełniony brakującymi polami z @p drugi
Dane polacz(const Dane& pierwszy, const Dane& drugi);
/// Tytuły generowane przez programy ("Microsoft Word - plik.docx", "untitled", "plik.pdf") nie niosą informacji
bool czyTytulSmieciowy(const std::string& tytul);
/// Autor wpisany przez program lub skaner ("Test", "Administrator", nicki z cyframi)
bool czyAutorSmieciowy(const std::string& autor);
/// Opis wpisany przez program ("Created PDF", "Generated by...")
bool czyOpisSmieciowy(const std::string& opis);
/// Kod języka ("pl", "pol", "en-US") -> polska nazwa; nieznany kod zwracany bez zmian
std::string nazwaJezyka(const std::string& kod);

/// Czyta metadane z pliku PDF albo EPUB (implementacja w Logika/OdczytMetadanych.cpp; wymaga wxBase i pdfinfo dla Info PDF)
Dane odczytaj(const std::string& sciezka);

} // namespace MetadaneKsiazek

#endif // METADANEKSIAZEK_H
